#!/usr/bin/env python3
"""Generate, build and run tools/gate_emu.c, then check two things offline:

  1. the *real* gate bytes reproduce the on-device name fingerprint (deny iff the part after
     the last '/' is exactly "su") -- this is the second, independent method for the gate
     semantics (the first being the disassembly + the 2026-10-14 device run);
  2. the single 4-byte patch (b.ne -> b, ledger §158/§181) makes every name return 0, i.e.
     the patch is sufficient and changes nothing else.

usage: python3 tools/gate_emu.py [--build]
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
IMG = os.path.join(ROOT, "fw", "Image")
TEXT_BASE = 0xFFFFFFC000080000
FINGER = os.path.join(ROOT, "art", "sgt-20261014-enforcing.txt")

GATE = 0xFFFFFFC000332688
GATE_END = 0xFFFFFFC0003326E4          # exclusive: the `ret` is at 0x3326e0
BL_STRRCHR = 0xFFFFFFC00033269C
BL_HELPER = 0xFFFFFFC0003326CC
PATCH_SITE = 0xFFFFFFC0003326B4
EXPECT_BL1_TARGET = 0xFFFFFFC000493FF0   # strrchr (kallsyms T hit, checked here)
EXPECT_BL2_TARGET = 0xFFFFFFC0003324A0   # helper
ORIG_WORD = 0x54000121                   # b.ne  -> allow exit
PATCH_WORD = 0x14000009                  # b     -> allow exit

D = "/data/local/tmp/sgt"
CASES = [
    (D + "/su", "control_su", "deny"),
    (D + "/sux", "control_sux", "allow"),
    (D + "/l1/su", "symlink_NAMED_su_to_sux_real", "deny"),
    (D + "/s2/../su", "dotdot_normalisation", "deny"),
    (D + "/s2/su", "file_su_in_subdir", "deny"),
    (D + "/su/pay_in_sudir", "pay_under_dir_named_su", "allow"),
    (D + "/sudir/pay_in_sudir", "sudir_as_component", "allow"),
    (D + "/su2", "name_su2", "allow"),
    (D + "/sU", "name_sU", "allow"),
    (D + "/SU", "name_SU", "allow"),
    (D + "/.su", "name_dot_su", "allow"),
    (D + "/su.sh", "name_su_sh", "allow"),
    (D + "/xsu", "name_xsu", "allow"),
    (D + "/asu", "name_asu", "allow"),
    (D + "/su-", "name_su_dash", "allow"),
    (D + "/su ", "name_su_space", "allow"),
    (D + "/s", "name_s", "allow"),
    (D + "/u", "name_u", "allow"),
    ("/system/bin/su", "path_system_su", "deny"),
    ("/proc/self/fd/3", "fdexec_proc_self_fd_of_su", "allow"),
    ("/data/local/tmp/SU", "caps_SU", "allow"),
]


def word(img, va):
    return int.from_bytes(img[va - TEXT_BASE: va - TEXT_BASE + 4], "little")


def bl_target(w, site):
    imm = w & 0x03FFFFFF
    if imm & 0x02000000:
        imm -= 0x04000000
    return site + imm * 4


def emit_header():
    img = open(IMG, "rb").read()
    data = img[GATE - TEXT_BASE: GATE_END - TEXT_BASE]
    checks = [
        (word(img, PATCH_SITE) == ORIG_WORD, "patch site holds b.ne 0x54000121"),
        (bl_target(word(img, BL_STRRCHR), BL_STRRCHR) == EXPECT_BL1_TARGET,
         "BL1 -> strrchr@%x" % EXPECT_BL1_TARGET),
        (bl_target(word(img, BL_HELPER), BL_HELPER) == EXPECT_BL2_TARGET,
         "BL2 -> helper@%x" % EXPECT_BL2_TARGET),
        (word(img, GATE_END - 4) == 0xD65F03C0, "gate ends in `ret`"),
        ((word(img, GATE + 4) == 0x528005E1), "the char handed to strrchr is '/' (mov w1,#0x2f)"),
        (word(img, GATE + 0x20) == 0x52800000, "w0 = 0 is prepared before the compares"),
    ]
    for ok, what in checks:
        print("  %s %s" % ("OK  " if ok else "FAIL", what))
        if not ok:
            raise SystemExit("premise broken -- do not run the emulator against stale bytes")
    hdr = os.path.join(HERE, "gate_bytes.h")
    with open(hdr, "w") as fh:
        fh.write("/* generated by tools/gate_emu.py from fw/Image [%x,%x) -- do not edit */\n"
                 % (GATE, GATE_END))
        fh.write("static const unsigned char gate_bytes[] = {%s};\n"
                 % ",".join(str(b) for b in data))
        fh.write("#define GATE_LEN %d\n" % len(data))
        for name, va in (("GATE_SITE_BL1", BL_STRRCHR), ("GATE_SITE_BL2", BL_HELPER),
                         ("GATE_SITE_PATCH", PATCH_SITE)):
            fh.write("#define %s 0x%x\n" % (name, va - GATE))
        fh.write("#define GATE_ORIG_WORD 0x%08x\n" % ORIG_WORD)
        fh.write("#define GATE_PATCH_WORD 0x%08x\n" % PATCH_WORD)
    print("  wrote %s (%d bytes of code)" % (hdr, len(data)))


CC = ("/home/v/Android/Sdk/ndk/29.0.13846066/toolchains/llvm/prebuilt/linux-x86_64/bin/"
      "aarch64-linux-android23-clang")


def build():
    out = os.path.join(HERE, "gate_emu")
    r = subprocess.run([CC, "-O1", "-static", "-o", out, os.path.join(HERE, "gate_emu.c")],
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    print(r.stdout.decode(errors="replace").strip())
    if r.returncode != 0:
        raise SystemExit("compile failed rc=%d -- never run a stale binary" % r.returncode)
    print("  built %s" % out)
    return out


def run(binary, mode):
    inp = "".join(c[0] + "\n" for c in CASES)   # CASES = (path, label, expect): feed the PATH
    p = subprocess.run(["qemu-aarch64", binary, mode], input=inp.encode(),
                       stdout=subprocess.PIPE, stderr=subprocess.STDOUT, timeout=180)
    lines = p.stdout.decode(errors="replace").splitlines()
    head = [l for l in lines if l.startswith("#")]
    res = {}
    for l in lines:
        m = re.match(r"^(-?\d+) (.*)$", l)
        if m:
            res[m.group(2)] = int(m.group(1))
    return head, res, p.returncode


def device_expectations():
    """The 2026-10-14 on-device run, for the labels our cases can be matched to."""
    want = {}
    if not os.path.exists(FINGER):
        return want
    for line in open(FINGER, errors="replace"):
        m = re.match(r"^CASE\s+(\S+)\s+->\s+(.*)$", line)
        if not m:
            continue
        label, verdict = m.group(1), m.group(2)
        if "errno=1" in verdict:
            want[label] = "deny"
        elif "RAN" in verdict or "WARNING" in verdict or "linker" in verdict:
            want[label] = "allow"
    return want


def main():
    print("== premises from fw/Image ==")
    emit_header()
    binary = build()

    print("\n== run: original bytes ==")
    h1, orig, rc1 = run(binary, "orig")
    print("  " + (h1[0] if h1 else "no header"))
    print("== run: patched bytes (b.ne -> b) ==")
    h2, patched, rc2 = run(binary, "patched")
    print("  " + (h2[0] if h2 else "no header"))
    if rc1 or rc2:
        raise SystemExit("emulator failed rc=%d/%d" % (rc1, rc2))

    want = device_expectations()
    bad = []
    print("\n%-34s %-8s %-8s %-8s" % ("path", "gate", "expect", "device"))
    for path, label, expect in CASES:
        g = "deny" if orig.get(path, 0) < 0 else "allow"
        p = "deny" if patched.get(path, 0) < 0 else "allow"
        d = want.get(label, "-")
        print("%-34s %-8s %-8s %-8s" % (path.replace(D, "..."), g, expect, d))
        if g != expect:
            bad.append("original bytes: %s -> %s, expected %s" % (path, g, expect))
        if p != "allow":
            bad.append("PATCHED bytes still deny %s (rc=%d)" % (path, patched.get(path)))
        if d != "-" and g != d:
            bad.append("emulator disagrees with the device run on %s (%s vs %s)" % (label, g, d))

    n_dev = sum(1 for _, l, _ in CASES if l in want)
    print("\ncompared against the recorded device fingerprint on %d/%d labels" % (n_dev, len(CASES)))
    for b in bad:
        print("  MISMATCH: " + b)
    if bad:
        print("\nVERDICT: not established -- resolve the mismatches before touching the phone")
        return 1
    print("\nVERDICT: real gate bytes reproduce the measured behaviour, and the single "
          "4-byte patch makes every name allow => one write is sufficient")
    return 0


if __name__ == "__main__":
    sys.exit(main())
