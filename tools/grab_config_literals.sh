#!/usr/bin/env bash
# SU names the privileged-exec client.  The official 7.1.1 firmware refuses execve of any path # whose last component is exactly "su" (ledger 579), so on that machine run these tools with SU=sux.
SU=${SU:-su}
# tools/grab_config_literals.sh -- for every /system/etc config path literal that a shipped binary
# names, record whether the DEVICE actually holds that file (state + size + md5).  The only device
# write is one scratch script under /data/local/tmp, removed at the end (ledger 410).
#
# Why: tools/shipped_disposition.py answers "which captured file has which reader".  This is the
# reverse leg -- "what do the binaries ask for that the extract never held".  It found
# /system/etc/diag.cfg and /system/etc/drc/drc_cfg_AZ.txt (both present on the device, never
# captured) and showed that /system/etc/drc exists at all, which corrected the §212 note claiming
# it did not.
#
# Usage: bash tools/grab_config_literals.sh [outfile]      (default /tmp/config-literals.tsv)
set -u
ROOT=${AUDIO_PORT_ROOT:-/home/v/.local/project/xplay6}
BASE=$ROOT/art/audio-6.0.1
OUT=${1:-/tmp/config-literals.tsv}

python3 - "$BASE" > /tmp/config-literals.list <<'PY' || exit 1
import os, re, sys
rx = re.compile(rb"/(?:system/)?etc/[a-zA-Z0-9_.\-/]{2,60}?\.(?:xml|conf|txt|cfg)")
out = set()
for root, dirs, fs in os.walk(os.path.join(sys.argv[1], "shipped")):
    for f in fs:
        if f.endswith(".so"):
            blob = open(os.path.join(root, f), "rb").read()
            out.update(m.group().decode() for m in rx.finditer(blob))
for p in sorted(out):
    print(p)
PY

N=$(grep -c . /tmp/config-literals.list)
[ "$N" -gt 0 ] || { echo "gate: no config literal found in any shipped .so -- nothing to probe"; exit 1; }
echo "probing $N config path literals on the device"

python3 - /tmp/config-literals.list > /tmp/litprobe.sh <<'PY' || exit 1
import sys
paths = [l.strip() for l in open(sys.argv[1]) if l.strip()]
for p in paths:
    if "'" in p or '"' in p or " " in p:
        sys.exit("gate: unexpected character in literal " + repr(p))
lines = ["# generated by tools/grab_config_literals.sh -- paths come from the extract itself",
         "for f in \\"]
lines += ["    " + p + (" \\" if i < len(paths) - 1 else " ; do") for i, p in enumerate(paths)]
lines += ['  if [ -f "$f" ]; then',
          '    s=$(toybox stat -c %s "$f")',
          '    m=$(md5sum "$f")',
          '    echo "$f PRESENT $s ${m%% *}"',
          "  else",
          '    echo "$f ABSENT"',
          "  fi",
          "done"]
print("\n".join(lines))
PY

adb push /tmp/litprobe.sh /data/local/tmp/litprobe.sh >/dev/null 2>&1 || {
  echo "gate: adb push failed -- cannot probe"; exit 1; }
adb exec-out "$SU -c 'sh /data/local/tmp/litprobe.sh'" 2>/dev/null | tr -d "\r" > /tmp/litprobe.out
adb exec-out "$SU -c 'rm -f /data/local/tmp/litprobe.sh'" >/dev/null 2>&1

python3 - "$BASE" /tmp/config-literals.list /tmp/litprobe.out "$OUT" <<'PY' || exit 1
import os, sys
base, lst, dev, out = sys.argv[1:5]
paths = [l.strip() for l in open(lst, encoding="utf-8") if l.strip()]
res = {}
for line in open(dev, encoding="utf-8", errors="replace"):
    p = line.split()
    if len(p) >= 4 and p[1] == "PRESENT":
        res[p[0]] = ("PRESENT", p[2], p[3])
    elif len(p) >= 2 and p[1] == "ABSENT":
        res[p[0]] = ("ABSENT", "", "")
have = set()
for root, dirs, fs in os.walk(os.path.join(base, "shipped")):
    for f in fs:
        have.add(f)
unprobed = [p for p in paths if p not in res]
rows = ["literal\tdevice_state\tbytes\tmd5\tin_extract"]
for p in paths:
    st, b, m = res.get(p, ("NOT-PROBED", "", ""))
    rows.append(f"{p}\t{st}\t{b}\t{m}\t{'yes' if os.path.basename(p) in have else 'no'}")
open(out, "w", encoding="utf-8").write("\n".join(rows) + "\n")
if unprobed:
    sys.exit("gate: %d of %d literals got no device answer (%s) -- the probe script did not run "
             "cleanly, do not trust this table" % (len(unprobed), len(paths), unprobed[:3]))
pre = sum(1 for p in paths if res[p][0] == "PRESENT")
print("wrote %s: %d literals, %d PRESENT on device, %d ABSENT, %d already in the extract" %
      (out, len(paths), pre, len(paths) - pre,
       sum(1 for p in paths if os.path.basename(p) in have)))
PY
