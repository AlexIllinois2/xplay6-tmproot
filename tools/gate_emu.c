/* tools/gate_emu.c -- run the *actual* gate instruction bytes (fw/Image 0x332688..0x3326e4)
 * under qemu-aarch64, with its two out-of-line calls redirected to harness stubs, and
 * report the return value for every path handed in on stdin.
 *
 * This is the offline half of "does one 4-byte patch do the job": the pre-patch column must
 * reproduce the behaviour we measured on the phone (deny iff the last component after
 * strrchr('/') is exactly "su"), and the post-patch column must return 0 for everything.
 * Doing it with the real bytes -- not with my re-reading of them -- is the point.
 *
 *   argv[1] = orig | patched
 *   stdin   = one path per line
 *   stdout  = "<rc> <path>"  (rc<0 == deny, 0 == allow)
 *
 * Gate structure being exercised (ledger §155/§179/§181):
 *   x19 = x0; c = '/'; p = strrchr(x0, c); x19 = basename(x19, p)
 *   w0 = 0                       <-- the "allow" value is prepared first
 *   cmp byte[x19], 's' / 'u' / terminator  -> any mismatch jumps to the epilogue (return 0)
 *   bl helper                    -> w0 = helper()!=0 ? -1 : 0
 */
#define _GNU_SOURCE
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/mman.h>

#include "gate_bytes.h"     /* gate_bytes[], GATE_LEN, GATE_SITE_BL1/BL2, GATE_SITE_PATCH,
                               GATE_ORIG_WORD, GATE_PATCH_WORD  (generated by tools/gate_emu.py) */

static long helper_returns = 1;      /* 1 == "feature says deny" (the state measured on the phone) */
static int dbg = 0;

static long h_strrchr(const char *s, long c)
{
    char *p = strrchr(s, (int)c);
    if (dbg)
        fprintf(stderr, "  strrchr(\"%s\", '%c') = %s -> basename \"%s\"\n",
                s, (int)c, p ? "hit" : "NULL", p ? p + 1 : s);
    return (long)(uintptr_t)p;
}

static long h_helper(void)
{
    if (dbg)
        fprintf(stderr, "  helper() called -> %ld\n", helper_returns);
    return helper_returns;
}

static unsigned int *copy_at(unsigned long want)
{
    return mmap((void *)want, 0x1000, PROT_READ | PROT_WRITE | PROT_EXEC,
                MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
}

/* rewrite one BL in the copy so it reaches <target>; fail loudly if it is out of range */
static int relink(unsigned int *code, unsigned long code_addr, unsigned int off, void *target)
{
    unsigned long site = code_addr + off;
    long delta = (long)((unsigned long)(uintptr_t)target - site);
    if (delta / 4 > 0x7FFFFFF || delta / 4 < -0x8000000)
        return -1;
    code[off / 4] = 0x94000000 | ((unsigned int)((delta >> 2) & 0x03FFFFFF));
    return 0;
}

int main(int argc, char **argv)
{
    const char *mode = argc > 1 ? argv[1] : "orig";
    int patched = strcmp(mode, "patched") == 0;
    dbg = argc > 2;
    unsigned int *code = NULL;
    unsigned long code_addr = 0;

    /* the copy has to sit within +/-128 MB of the stubs for BL to reach them.
     * mmap's first argument is only a hint, so the *returned* address is what counts. */
    unsigned long anchor = (unsigned long)(uintptr_t)&h_strrchr & ~0xfffUL;
    for (long step = -0x400000; step <= 0x400000; step += 0x10000) {
        unsigned long want = anchor + step;
        if (want < 0x10000)
            continue;
        code = copy_at(want);
        if (code == MAP_FAILED)
            continue;
        code_addr = (unsigned long)(uintptr_t)code;
        long d1 = (long)((unsigned long)(uintptr_t)&h_strrchr) - (long)(code_addr + GATE_SITE_BL1);
        long d2 = (long)((unsigned long)(uintptr_t)&h_helper) - (long)(code_addr + GATE_SITE_BL2);
        if (d1 / 4 > 0x7FFFFFF || d1 / 4 < -0x8000000 ||
            d2 / 4 > 0x7FFFFFF || d2 / 4 < -0x8000000) {
            munmap(code, 0x1000);
            code = NULL;
            continue;
        }
        break;
    }
    if (!code) {
        fprintf(stderr, "no code page within BL range of the stubs\n");
        return 2;
    }
    memcpy(code, gate_bytes, GATE_LEN);
    if (relink(code, code_addr, GATE_SITE_BL1, (void *)&h_strrchr) != 0 ||
        relink(code, code_addr, GATE_SITE_BL2, (void *)&h_helper) != 0) {
        fprintf(stderr, "CONTROL FAIL: stubs out of BL range\n");
        return 2;
    }
    /* sanity: the site we may change must still hold the word read out of the image */
    if (code[GATE_SITE_PATCH / 4] != GATE_ORIG_WORD) {
        fprintf(stderr, "CONTROL FAIL: site word %08x != image %08x\n",
                code[GATE_SITE_PATCH / 4], GATE_ORIG_WORD);
        return 2;
    }
    if (patched)
        code[GATE_SITE_PATCH / 4] = GATE_PATCH_WORD;
    __builtin___clear_cache((char *)code, (char *)code + GATE_LEN);

    printf("# mode=%s helper=%ld code=%#lx bl1=%08x bl2=%08x patch_site=%08x\n",
           mode, helper_returns, code_addr, code[GATE_SITE_BL1 / 4], code[GATE_SITE_BL2 / 4],
           code[GATE_SITE_PATCH / 4]);

    char line[512];
    /* the gate's return value lives in w0, and a 32-bit write zeroes the top of x0,
     * so -1 arrives as 0x00000000FFFFFFFF -- read it as the C int the kernel returns. */
    int(*gate)(const char *) = (int (*)(const char *))(uintptr_t)code_addr;
    while (fgets(line, sizeof line, stdin)) {
        size_t n = strlen(line);
        while (n && (line[n - 1] == '\n' || line[n - 1] == '\r'))
            line[--n] = 0;
        if (!n)
            continue;
        printf("%d %s\n", gate(line), line);
        if (fflush(stdout) != 0)
            return 1;
    }
    return 0;
}
